import Foundation

@main enum ExerciseTests {
    static func main() {
        var policy = ExercisePolicy()
        precondition(!policy.tick(now: 0, eligible: true, enabled: true, minutes: 20))
        _ = policy.tick(now: 1200, eligible: true, enabled: true, minutes: 20)
        precondition(policy.due)
        policy.later(now: 1200)
        _ = policy.tick(now: 1499, eligible: true, enabled: true, minutes: 20)
        precondition(!policy.due)
        _ = policy.tick(now: 1500, eligible: true, enabled: true, minutes: 20)
        precondition(policy.due)
        policy.start(.reset, now: 1500)
        precondition(policy.active && !policy.due)
        _ = policy.tick(now: 1509, eligible: true, enabled: true, minutes: 20)
        precondition(policy.snapshot(now: 1509)["step"] as? String == "blink")
        precondition(policy.snapshot(now: 1510)["step"] as? String == "look")
        policy.pause(now: 1512)
        precondition(policy.snapshot(now: 1600)["remaining"] as? Double == 18)
        precondition(!policy.tick(now: 1600, eligible: true, enabled: true, minutes: 20))
        policy.resume(now: 1600)
        precondition(!policy.tick(now: 1617, eligible: true, enabled: true, minutes: 20))
        precondition(policy.tick(now: 1618, eligible: true, enabled: true, minutes: 20))
        precondition(!policy.tick(now: 1619, eligible: true, enabled: true, minutes: 20))
        precondition(policy.phase == .completed)
        policy.end(now: 1620)
        policy.start(.blink, now: 1620)
        _ = policy.tick(now: 1625, eligible: false, enabled: true, minutes: 20)
        precondition(!policy.active && !policy.due)
        _ = policy.tick(now: 10000, eligible: true, enabled: true, minutes: 20)
        precondition(!policy.due)
        _ = policy.tick(now: 11199, eligible: true, enabled: true, minutes: 20)
        precondition(!policy.due)
        _ = policy.tick(now: 11200, eligible: true, enabled: true, minutes: 20)
        precondition(policy.due)
        _ = policy.tick(now: 11201, eligible: true, enabled: false, minutes: 20)
        precondition(!policy.due)
        policy.start(.look, now: 11202)
        precondition(policy.snapshot(now: 11203)["step"] as? String == "look")
        precondition(policy.tick(now: 11222, eligible: true, enabled: false, minutes: 20))
        policy.start(.blink, now: .nan)
        precondition(policy.phase == .completed)
        policy.end(now: 12000)
        _ = policy.tick(now: 12000, eligible: true, enabled: true, minutes: .infinity)
        precondition(!policy.due)
        _ = policy.tick(now: 13200, eligible: true, enabled: true, minutes: .infinity)
        precondition(policy.due)
        _ = policy.tick(now: 13201, eligible: true, enabled: true, minutes: 5)
        precondition(!policy.due)
        print("Exercise policy passed: phases, pause clock, one completion, one snooze, cancellation, no backlog, optional scheduling, finite bounds")
    }
}
